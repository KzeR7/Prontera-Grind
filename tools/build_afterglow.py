#!/usr/bin/env python3
"""Extract the current Canvas choreography without preview UI or stand-ins."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tools/skill-fx-proposals/afterglow-v8.html'
OUTPUT = ROOT / 'assets/afterglow-animations.js'
BASELINE = ROOT / 'tools/skill-fx-proposals/afterglow-v8-baseline.js'
CHOICES = ROOT / 'tools/skill-fx-proposals/owner-choices.json'


def build_baseline():
    source = SOURCE.read_text()
    catalog = source[source.index('const FX='):source.index('const PASSIVES=')]
    helpers = source[source.index('const $='):source.index('const ground=')]
    helpers = helpers.replace('const $=id=>document.getElementById(id),', 'const ')
    animation = source[source.index('// Tapered layered cuts:'):source.index('function renderSkill(')]
    return (
        '// Generated by python3 tools/build_afterglow.py from the Arcana II V8 effect source.\n'
        '// Regenerate after editing the proposal; no native character art is included.\n'
        "'use strict';\nconst PGAfterglowAnimations=(()=>{\n" + catalog +
        'return {catalog:FX.filter(f=>f.type!=="concept"),create(g){\n'
        'const TAU=Math.PI*2;let quality=1;\n' + helpers + animation +
        'return (id,t,detail=1)=>{quality=detail;materialTime=t;prepareSkill(id);const fn=ANIM[id];if(fn){buffLight(id,t);fn(t);}};\n'
        '}};\n})();\n'
    )


def build():
    baseline = build_baseline()
    report = json.loads(CHOICES.read_text())
    old_path = ROOT / report['sources']['old']['path']
    old_source = old_path.read_text()
    # Refuse to reinterpret the submitted choices against different effect sources.
    for key, content in [('old', old_path.read_bytes()), ('new', baseline.encode()),
                         ('adapter', (ROOT / 'assets/skill-afterglow.js').read_bytes()),
                         ('materials', (ROOT / 'assets/skill-materials.js').read_bytes())]:
        if hashlib.sha256(content).hexdigest() != report['sources'][key]['sha256']:
            raise ValueError('Submitted FX source differs: ' + key)
    rows = report['skills']
    catalog_text = baseline[baseline.index('const FX=') + 9:baseline.index('return {catalog:')].strip().rstrip(';')
    ids = {f['id'] for f in json.loads(catalog_text) if f['type'] != 'concept'}
    active = [row for row in rows if row['choice'] != 'no-fx']
    if len({row['id'] for row in rows}) != len(rows) or {row['id'] for row in active} != ids:
        raise ValueError('Submitted choices must cover every rendered skill exactly once')
    if any(row['choice'] not in ('old', 'new', 'undecided', 'no-fx') for row in rows):
        raise ValueError('Unsupported FX choice')
    choices = {row['id']: row['choice'] for row in active}
    old_ids = [row['id'] for row in active if row['choice'] == 'old']
    helpers = old_source[old_source.index('const $='):old_source.index('const ground=')]
    helpers = helpers.replace('const $=id=>document.getElementById(id),', 'const ')
    animation = old_source[old_source.index('// Tapered layered cuts:'):old_source.index('function renderSkill(')]
    # V7 keeps its shared helpers, but ship only the selected animation bodies.
    matches = list(re.finditer(r'^ANIM\.([A-Za-z0-9_]+)=', animation, re.MULTILINE))
    prefix = animation[:matches[0].start()]
    animation = prefix + ''.join(animation[m.start():matches[i + 1].start() if i + 1 < len(matches) else len(animation)]
                                 for i, m in enumerate(matches) if m.group(1) in old_ids)
    old_adjustments = (ROOT / 'tools/skill-fx-proposals/owner-fx-old.js').read_text()
    new_adjustments = (ROOT / 'tools/skill-fx-proposals/owner-fx-new.js').read_text()
    redesign = (ROOT / 'tools/skill-fx-proposals/owner-fx-redo.js').read_text()
    redo_ids = re.findall(r'^ANIM\.([A-Za-z0-9_]+)=', redesign, re.MULTILINE)
    if len(redo_ids) != len(set(redo_ids)) or set(redo_ids) != {row['id'] for row in active if row['choice'] == 'undecided'}:
        raise ValueError('Redo overrides must match the eight originally undecided skills')
    # Retain only V7 helpers reachable from the selected animation bodies.
    shared = helpers + animation[:animation.index('const ANIM=')]
    statements = list(re.finditer(r'^(?:function|const) ([A-Za-z0-9_]+)', shared, re.MULTILINE))
    functions = {}
    for i, match in enumerate(statements):
        if shared[match.start():].startswith('function '):
            end = statements[i + 1].start() if i + 1 < len(statements) else len(shared)
            functions[match.group(1)] = (match.start(), end, shared[match.start():end])
    roots = animation[animation.index('const ANIM='):] + old_adjustments
    # Include references from retained constants as well as direct animation calls.
    constants = shared
    for start, end, _ in sorted(functions.values(), reverse=True):
        constants = constants[:start] + constants[end:]
    used = set()
    pending = [roots + constants]
    while pending:
        text = pending.pop()
        for name, (_, _, body) in functions.items():
            if name not in used and re.search(r'\b' + re.escape(name) + r'\b', text):
                used.add(name)
                pending.append(body)
    for name, (start, end, _) in sorted(functions.items(), key=lambda item: item[1][0], reverse=True):
        if name not in used:
            shared = shared[:start] + shared[end:]
    helpers = shared
    animation = animation[animation.index('const ANIM='):]
    legacy = ('const ownerLegacy={create(g){const TAU=Math.PI*2;let quality=1;\n' +
              helpers + animation + old_adjustments +
              '\nreturn(id,t,detail)=>{quality=detail;ANIM[id]?.(t)};}};\n')
    # Chosen V7 effects do not need a duplicate V8 animation body in the live bundle.
    selected = baseline
    boundaries = list(re.finditer(r'^(?:ANIM\.([A-Za-z0-9_]+)=|function |const |return \(id)', selected, re.MULTILINE))
    for i in range(len(boundaries) - 1, -1, -1):
        match = boundaries[i]
        if match.group(1) in old_ids + redo_ids:
            end = boundaries[i + 1].start() if i + 1 < len(boundaries) else len(selected)
            selected = selected[:match.start()] + selected[end:]
    runtime = selected.replace('// Generated by python3 tools/build_afterglow.py from the Arcana II V8 effect source.',
                               '// Generated by python3 tools/build_afterglow.py from V7/V8, owner-choices.json and owner FX adjustments.')
    runtime = runtime.replace('const PGAfterglowAnimations=(()=>{\n',
                              'const PGAfterglowAnimations=(()=>{\n' + legacy +
                              'const ownerOld=new Set(' + json.dumps(old_ids) + ');\n')
    runtime = runtime.replace('return {catalog:FX.filter',
                              'return {redesigned:Object.freeze(' + json.dumps(redo_ids) + '),choices:Object.freeze(' + json.dumps(choices) + '),catalog:FX.filter')
    runtime = runtime.replace('create(g){\nconst TAU=Math.PI*2;let quality=1;\nconst cl=',
                              'create(g){\nconst ownerOldPaint=ownerLegacy.create(g);\nconst TAU=Math.PI*2;let quality=1;\nconst cl=')
    # Insert only inside the V8 closure; old helpers remain an independent namespace.
    marker = 'return (id,t,detail=1)=>{quality=detail;'
    runtime = runtime.replace(marker, new_adjustments + '\n' + redesign + '\n' + marker +
                              'if(ownerOld.has(id)){ownerOldPaint(id,t,detail);return;}')
    # Source comments remain in the authored files; omit comment-only lines from the shipped bundle.
    source = (ROOT / 'index.html').read_text()
    fourth = json.loads('[' + source.split('const SKILLS4=[', 1)[1].split('\n];', 1)[0] + ']')
    rows = [[sk['id'], sk['n'], sk['from'], sk['col'], sk['visual'], sk.get('hits', 1), sk['type'], sk.get('spacing', .5)] for sk in fourth]
    fourth_source = (ROOT / 'tools/skill-fx-proposals/fourth-job-fx.js').read_text()
    runtime += '\n' + fourth_source.replace('/* FOURTH_SKILL_ROWS */[]', json.dumps(rows, separators=(',', ':')))

    return '\n'.join(line.strip() for i, line in enumerate(runtime.splitlines())
                     if line.strip() and (i < 2 or not line.lstrip().startswith('//'))) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    baseline = build_baseline()
    content = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Afterglow runtime is stale; run python3 tools/build_afterglow.py')
        if not BASELINE.exists() or BASELINE.read_text() != baseline:
            raise SystemExit('Afterglow comparison baseline is stale; run python3 tools/build_afterglow.py')
        print('Afterglow runtime and preserved V8 baseline match the sources and owner choices')
    else:
        BASELINE.write_text(baseline)
        OUTPUT.write_text(content)
        print('Generated assets/afterglow-animations.js')
