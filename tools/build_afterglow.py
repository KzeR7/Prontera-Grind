#!/usr/bin/env python3
"""Extract the owner's approved Canvas choreography without preview UI or stand-ins."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tools/skill-fx-proposals/afterglow-v6.html'
OUTPUT = ROOT / 'assets/afterglow-animations.js'


def build():
    source = SOURCE.read_text()
    catalog = source[source.index('const FX='):source.index('const PASSIVES=')]
    helpers = source[source.index('const $='):source.index('const ground=')]
    helpers = helpers.replace('const $=id=>document.getElementById(id),', 'const ')
    animation = source[source.index('// A filled ribbon'):source.index('function renderSkill(')]
    return (
        '// Generated by python3 tools/build_afterglow.py from the approved Afterglow V6 study.\n'
        '// Regenerate after editing the proposal; no native character art is included.\n'
        "'use strict';\nconst PGAfterglowAnimations=(()=>{\n" + catalog +
        'return {catalog:FX.filter(f=>f.type!=="concept"),create(g){\n'
        'const TAU=Math.PI*2;let quality=1;\n' + helpers + animation +
        'return (id,t,detail=1)=>{quality=detail;const fn=ANIM[id];if(fn)fn(t);};\n'
        '}};\n})();\n'
    )


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Afterglow runtime is stale; run python3 tools/build_afterglow.py')
        print('Afterglow runtime matches the approved proposal')
    else:
        OUTPUT.write_text(content)
        print('Generated assets/afterglow-animations.js')
