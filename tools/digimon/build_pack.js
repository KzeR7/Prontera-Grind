#!/usr/bin/env node
'use strict';

/**
 * Build the complete, lazy-loaded Digimon animation pack from the pinned source.
 *
 *   npm install --no-save --package-lock=false sharp@0.35.2
 *   node tools/digimon/build_pack.js /path/to/digimon-up-sprites
 *
 * The source checkout must be revision 4eaee71cc949953e45ce5a77564469ba93e36907.
 * Output is assets/digimon/v3 plus the small shared assets/digimon/roster.js.
 * Every form has one lossless WebP atlas and one JSON frame record. The browser
 * downloads those two files only when that form is actually shown.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const cp = require('node:child_process');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'assets', 'digimon', 'v3');
const ROSTER_OUT = path.join(ROOT, 'assets', 'digimon', 'roster.js');
const SOURCE_URL = 'https://github.com/dannyphang/digimon-up-sprites';
const REVISION = '4eaee71cc949953e45ce5a77564469ba93e36907';
const EXPECTED_ENTRIES = 280;
const EXPECTED_FRAMES = 17666;
const ACTIONS = ['idle', 'walking', 'attack', 'faint'];
const NAME_OVERRIDES = {
  blackwargreymon: 'BlackWarGreymon',
  malomyotismon: 'MaloMyotismon',
};
const VARIANT_LABELS = {
  adventure: 'Adventure',
  adventure02: 'Adventure 02',
  tamers: 'Tamers',
  normal: 'Normal',
  gold: 'Gold',
  beatbreak: 'Beatbreak',
  runevent: 'Run Event',
  runevent_fever: 'Run Event Fever',
  runevent_shadow: 'Run Event Shadow',
  xroswars: 'Xros Wars',
};
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
const title = id => id.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());

function sourceRevision(source) {
  try {
    const actual = cp.execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (actual !== REVISION) throw new Error(`expected ${REVISION}, got ${actual}`);
  } catch (error) {
    // An exported archive has no .git directory. A REVISION file lets a builder
    // preserve the same provenance check without requiring a Git checkout.
    let declared = '';
    try { declared = fs.readFileSync(path.join(source, 'REVISION'), 'utf8').trim(); } catch {}
    if (declared !== REVISION) {
      throw new Error(`Source revision must be ${REVISION}. Use the pinned Git checkout or an archive containing a matching REVISION file.`);
    }
  }
}

function buildRoster(source, ids) {
  const profiles = JSON.parse(fs.readFileSync(path.join(source, 'digimon.json'), 'utf8'));
  if (!Array.isArray(profiles) || profiles.length !== 251) throw new Error('Expected exactly 251 source profiles');
  const byProfile = new Map(profiles.map(profile => [profile.folder, profile]));
  const known = new Set(byProfile.keys());
  const entries = ids.map(id => {
    const direct = byProfile.get(id);
    let base = direct || null;
    if (!base) {
      const parts = id.split('_');
      for (let n = parts.length - 1; n > 0; n--) {
        const candidate = byProfile.get(parts.slice(0, n).join('_'));
        if (candidate) { base = candidate; break; }
      }
    }
    let name;
    if (direct) name = direct.name.en;
    else if (base) {
      const suffix = id.slice(base.folder.length + 1);
      name = `${base.name.en} (${VARIANT_LABELS[suffix] || title(suffix)})`;
    } else name = NAME_OVERRIDES[id] || title(id);
    return {
      id,
      name,
      stage: base?.stage?.en || null,
      attribute: base?.attribute?.en || null,
      type: base?.type?.en || null,
      profile: base?.folder || null,
      variant: !known.has(id),
      evolvesTo: base ? [...(base.evolves_to || [])] : [],
    };
  });
  const profiled = entries.filter(entry => entry.profile).length;
  const directProfiles = entries.filter(entry => byProfile.has(entry.id)).length;
  if (entries.length !== EXPECTED_ENTRIES || entries.filter(entry => entry.variant).length !== 32 || profiled !== 266 || directProfiles !== 248) {
    throw new Error(`Unexpected roster coverage: ${entries.length} entries, ${directProfiles} direct profiles, ${profiled} including inherited variant profiles`);
  }
  const js = `/* Generated by tools/digimon/build_pack.js from ${REVISION}.\n * 280 animation entries; 251 source profiles; no invented profile/evolution data. */\n` +
`(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;root.PGDigimonRoster=api})(globalThis,function(){\n'use strict';\n` +
`const ENTRIES=${JSON.stringify(entries)};\nconst IDS=ENTRIES.map(e=>e.id),BY_ID=Object.create(null);for(const e of ENTRIES)BY_ID[e.id]=e;\n` +
`const STAGES=['Baby I','Baby II','Rookie','Champion','Ultimate','Mega','Mega+','Armor'];\n` +
`const clean=id=>typeof id==='string'&&Object.hasOwn(BY_ID,id)?id:null;\n` +
`const entry=id=>BY_ID[clean(id)]||null;\n` +
`const name=id=>entry(id)?.name||String(id||'');\n` +
`const directEvolutions=id=>[...new Set((entry(id)?.evolvesTo||[]).filter(ref=>Object.hasOwn(BY_ID,ref)))];\n` +
`function visualScale(id){const stage=entry(id)?.stage;return ({'Baby I':.75,'Baby II':.85,Rookie:1,Champion:1.2,Ultimate:1.4,Mega:1.55,'Mega+':1.55,Armor:1.2})[stage]||1.1}\n` +
`return {IDS,ENTRIES,STAGES,PROFILE_COUNT:251,PROFILED_ENTRY_COUNT:${profiled},DIRECT_PROFILED_ENTRY_COUNT:${directProfiles},clean,entry,name,directEvolutions,visualScale};\n});\n`;
  fs.writeFileSync(ROSTER_OUT, js);
  return entries;
}

async function crop(file) {
  const source = fs.readFileSync(file);
  const image = sharp(source).ensureAlpha();
  const metadata = await image.metadata();
  const { data, info } = await image.raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3]) {
        if (x < left) left = x;
        if (x > right) right = x;
        if (y < top) top = y;
        if (y > bottom) bottom = y;
      }
    }
  }
  const canvas = [metadata.width, metadata.height];
  if (right < 0) return { data: Buffer.alloc(4), w: 1, h: 1, offset: [0, 0], canvas, sourceSha256: sha256(source) };
  const w = right - left + 1, h = bottom - top + 1, cropped = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) {
    data.copy(cropped, y * w * 4, ((top + y) * info.width + left) * 4, ((top + y) * info.width + left + w) * 4);
  }
  return { data: cropped, w, h, offset: [left, top], canvas, sourceSha256: sha256(source) };
}

async function packEntry(baked, id) {
  const records = Object.fromEntries(ACTIONS.map(action => [action, []]));
  const files = [];
  for (const action of ACTIONS) {
    const directory = path.join(baked, id, action);
    const names = fs.readdirSync(directory).filter(name => /^f_\d+\.png$/.test(name)).sort();
    if (names.length < 2) throw new Error(`${id}/${action}: expected at least two frames`);
    for (const filename of names) files.push({ action, filename, file: path.join(directory, filename) });
  }
  const frames = [];
  let maxWidth = 0, canvas = null;
  for (const item of files) {
    const frame = await crop(item.file);
    if (!canvas) canvas = frame.canvas;
    else if (canvas[0] !== frame.canvas[0] || canvas[1] !== frame.canvas[1]) throw new Error(`${id}: source canvas changed between frames`);
    frames.push({ ...item, ...frame });
    maxWidth = Math.max(maxWidth, frame.w);
  }
  const idle = frames.filter(frame => frame.action === 'idle');
  const left = Math.min(...idle.map(frame => frame.offset[0]));
  const top = Math.min(...idle.map(frame => frame.offset[1]));
  const right = Math.max(...idle.map(frame => frame.offset[0] + frame.w));
  const bottom = Math.max(...idle.map(frame => frame.offset[1] + frame.h));
  const width = maxWidth > 2048 ? 4096 : maxWidth > 1024 ? 2048 : 1024;
  if (maxWidth > width) throw new Error(`${id}: frame wider than atlas`);
  let x = 0, y = 0, row = 0;
  const placements = [];
  for (const frame of frames) {
    if (x + frame.w > width) { x = 0; y += row + 1; row = 0; }
    placements.push([frame, x, y]);
    records[frame.action].push({
      rect: [x, y, frame.w, frame.h],
      offset: frame.offset,
      source: frame.filename,
      sha256: frame.sourceSha256,
    });
    x += frame.w + 1;
    row = Math.max(row, frame.h);
  }
  const height = y + row;
  if (height > 16383) throw new Error(`${id}: atlas exceeds WebP height limit (${height})`);
  const atlas = Buffer.alloc(width * height * 4);
  for (const [frame, px, py] of placements) {
    for (let line = 0; line < frame.h; line++) {
      frame.data.copy(atlas, ((py + line) * width + px) * 4, line * frame.w * 4, (line + 1) * frame.w * 4);
    }
  }
  const image = `${id}.webp`;
  const target = path.join(OUT, image);
  await sharp(atlas, { raw: { width, height, channels: 4 } }).webp({ lossless: true, effort: 6 }).toFile(target);
  const bytes = fs.statSync(target).size;
  const record = {
    id,
    image,
    canvas,
    anchor: [(left + right) / 2, bottom],
    figureHeight: bottom - top,
    width,
    height,
    actions: records,
  };
  fs.writeFileSync(path.join(OUT, `${id}.json`), `${JSON.stringify(record)}\n`);
  return {
    entry: { image, meta: `${id}.json`, width, height, frames: files.length, bytes, sha256: sha256(fs.readFileSync(target)) },
    frames: files.length,
    bytes,
  };
}

async function main() {
  const source = process.argv[2];
  if (!source) throw new Error('Usage: node tools/digimon/build_pack.js /path/to/digimon-up-sprites');
  sourceRevision(source);
  const baked = path.join(source, 'baked');
  const ids = fs.readdirSync(baked, { withFileTypes: true }).filter(item => item.isDirectory()).map(item => item.name).sort();
  if (ids.length !== EXPECTED_ENTRIES) throw new Error(`Expected ${EXPECTED_ENTRIES} animation entries, found ${ids.length}`);
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const entries = buildRoster(source, ids);
  const catalog = { version: 3, source: SOURCE_URL, revision: REVISION, species: {} };
  let frames = 0, bytes = 0, completed = 0;
  for (const id of ids) {
    const result = await packEntry(baked, id);
    catalog.species[id] = result.entry;
    frames += result.frames;
    bytes += result.bytes;
    if (++completed % 25 === 0) console.log(`Packed ${completed}/${ids.length} entries`);
  }
  if (frames !== EXPECTED_FRAMES) throw new Error(`Expected ${EXPECTED_FRAMES} frames, packed ${frames}`);
  fs.writeFileSync(path.join(OUT, 'catalog.json'), `${JSON.stringify(catalog)}\n`);
  console.log(`Built ${entries.length} entries, ${frames} frames, ${(bytes / 1048576).toFixed(2)} MiB of lossless WebP images`);
  console.log(`Wrote ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, ROSTER_OUT)}`);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
