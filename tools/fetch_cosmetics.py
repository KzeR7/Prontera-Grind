#!/usr/bin/env python3
"""Fetch the first four-slot wardrobe sample; rebuild metadata without fetching by default.
Requires Pillow. Use --fetch for missing files only. Source art is never repainted.
"""
import argparse
import hashlib
import json
import urllib.parse
import urllib.request
from pathlib import Path
from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'Updates/cosmetics-preview/art'
VIEWS = {'S': 8, 'SE': 15, 'NE': 13, 'attack': 47}
API = 'https://assets.latam-tools.com.br/image'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true')
    args = parser.parse_args()
    DEST.mkdir(exist_ok=True)
    sets, sources = {}, []
    for mask in range(16):
        costume = bool(mask & 8)
        rec = {'files': {}, 'frames': {}, 'delays': {}, 'poses': {},
               'height': 94, 'anchor': [100, 158]}
        for view, action in VIEWS.items():
            name = f'{mask}-{view}.png'
            path = DEST / name
            query = {'job': 4054 if costume else 4008, 'outfit': int(costume),
                     'head': 40, 'headPalette': 0, 'gender': 'male',
                     'action': action, 'headgear': f'{69 if mask & 1 else 0},{3 if mask & 2 else 0}',
                     'garment': 1 if mask & 4 else 0, 'enableShadow': 'true',
                     'canvas': f'200x200+100+{146 if costume else 150}'}
            url = API + '?' + urllib.parse.urlencode(query)
            if not path.exists():
                if not args.fetch:
                    raise SystemExit(f'Missing {path}; run with --fetch')
                with urllib.request.urlopen(url, timeout=40) as response:
                    data = response.read()
                # Validate the response before putting it in the source tree.
                import io
                with Image.open(io.BytesIO(data)) as image:
                    image.verify()
                path.write_bytes(data)
                print('Fetched', name, flush=True)
            with Image.open(path) as image:
                assert image.size == (200, 200), name
                assert image.n_frames > 1, name
                image.seek(0)
                image.convert('RGBA').save(DEST / f'{mask}-{view}-still.png')
                boxes, delays = [], []
                for frame in ImageSequence.Iterator(image):
                    rgba = frame.convert('RGBA')
                    boxes.append(rgba.getbbox())
                    delays.append([round(frame.info['duration']), 1000])
                assert all(b and b[0] > 0 and b[1] > 0 and b[2] < 200 and b[3] < 200 for b in boxes), name
                left, top = min(b[0] for b in boxes), min(b[1] for b in boxes)
                right, bottom = max(b[2] for b in boxes), max(b[3] for b in boxes)
                rec['files'][view] = name
                rec['frames'][view] = image.n_frames
                rec['delays'][view] = delays
                rec['poses'][view] = [left, top, right-left, bottom-top]
            sources.append({'file': name, 'url': url, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        sets[str(mask)] = rec
    data = {'dir': 'art', 'class': 'Lord Knight', 'sex': 'm', 'sets': sets}
    (DEST / 'manifest.js').write_text('// Generated by tools/fetch_cosmetics.py; native RO attachment data.\nwindow.COSMETIC_SKINS=' + json.dumps(data, separators=(',', ':')) + ';\n')
    (DEST / 'sources.json').write_text(json.dumps({'provider': 'https://github.com/adsonpleal/ragassets',
        'art': 'Ragnarok Online / Gravity', 'reference': 'https://ro3.roglobal.com/',
        'note': 'Classic RO rendered art. No RO3 sprites are included. Costume is the Rune Knight alternate outfit used as an appearance only.',
        'files': sources}, indent=2) + '\n')
    print('Verified 16 combinations, 64 APNGs; wrote manifest and source hashes.')

if __name__ == '__main__':
    main()
