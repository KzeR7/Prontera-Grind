#!/usr/bin/env python3
"""Keep the parked visual review's skill descriptions tied to the actual game."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    source=(ROOT/'index.html').read_text()
    skills=json.loads('['+source.split('const SKILLS4=[',1)[1].split('\n];',1)[0]+']')
    assert len(skills)==30 and len({s['id'] for s in skills})==30
    content='// Generated by tools/build_fourth_job_review.py from SKILLS4.\nconst FOURTH_REVIEW_SKILLS='+json.dumps(skills,separators=(',',':'))+';\n'
    output=ROOT/'Updates/fourth-jobs/skills.js'
    if args.check:
        if output.read_text()!=content:raise SystemExit('Fourth-job review skills are stale')
        print('Fourth-job review matches all 30 current game skills')
    else:output.write_text(content)
